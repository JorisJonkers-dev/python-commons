"""Writes the Python type of identity's Principal contract from its JSON Schema, so a field the
contract adds reaches the adapter mechanically. It knows the shapes the schema uses: strings (with
an enum, or as a date-time read as a datetime), booleans, arrays of strings, and objects.

    python scripts/generate_principal.py   # rewrites src/jorisjonkers_commons/identity/principal.py
"""

import json
import re
import sys
import textwrap
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "contract" / "principal.schema.json"
GENERATED = ROOT / "src" / "jorisjonkers_commons" / "identity" / "principal.py"

HEADER = '''# Generated by scripts/generate_principal.py from the Principal contract's schema; do not edit.
"""The Principal identity states on every channel, as the pinned contract's schema describes it."""

from dataclasses import dataclass
from datetime import datetime
from typing import Literal
'''


def _snake(name: str) -> str:
    return re.sub(r"(?<!^)([A-Z])", r"_\1", name).lower()


def _pascal(name: str) -> str:
    return name[:1].upper() + name[1:]


def _comment(description: str | None, indent: str) -> str:
    if not description:
        return ""
    prefix = f"{indent}#: "
    lines = textwrap.wrap(description, 100, initial_indent=prefix, subsequent_indent=prefix)
    return "".join(f"{line}\n" for line in lines)


def _docstring(description: str | None) -> str:
    if not description:
        return ""
    lines = textwrap.wrap(description, 96)
    if len(lines) == 1:
        return f'    """{lines[0]}"""\n\n'
    body = "".join(f"    {line}\n" for line in lines)
    return f'    """{body.lstrip()}    """\n\n'


def _type_of(name: str, field: dict[str, Any], types: list[str]) -> str:
    if "enum" in field:
        values = ", ".join(f'"{v}"' for v in sorted(field["enum"]))
        types.append(f"{_comment(field.get('description'), '')}{_pascal(name)} = Literal[{values}]\n")
        return _pascal(name)
    kind = field.get("type")
    if kind == "string":
        return "datetime" if field.get("format") == "date-time" else "str"
    if kind == "boolean":
        return "bool"
    if kind == "array" and field.get("items", {}).get("type") == "string":
        return "tuple[str, ...]"
    if kind == "object":
        types.append(_dataclass(_pascal(name), field, types))
        return _pascal(name)
    raise ValueError(f'no Python type for {name} (type "{kind}")')


def _dataclass(name: str, schema: dict[str, Any], types: list[str]) -> str:
    required = set(schema.get("required", []))
    fields = schema.get("properties", {})
    ordered = [f for f in fields if f in required] + [f for f in fields if f not in required]
    lines = []
    for field in ordered:
        spec = fields[field]
        annotation = _type_of(field, spec, types)
        default = "" if field in required else " | None = None"
        lines.append(f"{_comment(spec.get('description'), '    ')}    {_snake(field)}: {annotation}{default}\n")
    return f"@dataclass(frozen=True)\nclass {name}:\n{_docstring(schema.get('description'))}{''.join(lines)}"


def generate(schema: dict[str, Any]) -> str:
    """The Python source of the Principal type, from the contract's schema."""
    types: list[str] = []
    principal = _dataclass(schema.get("title", "Principal"), schema, types)
    return HEADER + "\n" + "\n\n".join([*types, principal])


if __name__ == "__main__":  # pragma: no cover
    GENERATED.write_text(generate(json.loads(SCHEMA.read_text())))
    sys.stdout.write(f"wrote {GENERATED.relative_to(ROOT)}\n")
